// Concatenates the Apps Script source files into ONE file to paste into the editor.
// Usage: node tools/bundle.mjs          -> writes apps-script/dist/EmailHelper.gs
//        node tools/bundle.mjs --check  -> exits 1 if the bundle is out of date
import { readFileSync, writeFileSync, existsSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const dir = join(dirname(fileURLToPath(import.meta.url)), '..', 'apps-script');
const FILES = ['Code.gs', 'Rules.gs', 'Gmail.gs', 'Store.gs', 'Samples.gs'];
const header = `/**
 * EMAIL HELPER — Apps Script backend (all-in-one file).
 * GENERATED by tools/bundle.mjs from apps-script/*.gs. Don't edit this file; edit the sources.
 * Your personal settings live in a separate Config.gs (see SETUP.md).
 */
`;
const out = header + FILES.map((f) => `\n// ${'='.repeat(70)}\n// ${f}\n// ${'='.repeat(70)}\n\n` + readFileSync(join(dir, f), 'utf8').trim() + '\n').join('');
const target = join(dir, 'dist', 'EmailHelper.gs');
if (process.argv.includes('--check')) {
  const same = existsSync(target) && readFileSync(target, 'utf8') === out;
  console.log(same ? 'bundle up to date' : 'bundle OUT OF DATE: run node tools/bundle.mjs');
  process.exit(same ? 0 : 1);
}
writeFileSync(target, out);
console.log('wrote', target, `(${out.length} chars)`);
